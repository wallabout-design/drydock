// Turns the editor's browser files (src/editor/) into src/server/editor-assets.ts,
// so the server can answer /admin/editor.js and /admin/editor.css from a Worker,
// which has no files to read. Run by `npm run build`; commit the result.
import { readFileSync, writeFileSync } from 'node:fs';

const files = { EDITOR_JS: 'editor.js', EDITOR_CSS: 'editor.css', ITEM_FORM_JS: 'item-form.js', LIST_PAGE_JS: 'list-page.js' };
let out = '// Generated by scripts/build-assets.mjs from src/editor/. Do not edit by hand.\n';
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name} = ${JSON.stringify(readFileSync(new URL(`../src/editor/${file}`, import.meta.url), 'utf8'))};\n`;
}
writeFileSync(new URL('../src/server/editor-assets.ts', import.meta.url), out);
